CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY,
    username varchar(50) NOT NULL,
    password_hash varchar(255) NOT NULL,
    email varchar(100) NOT NULL,
    full_name varchar(100) NOT NULL,
    role varchar(16) NOT NULL DEFAULT 'STUDENT',
    is_active boolean NOT NULL DEFAULT true,
    token_version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_username_lowercase CHECK (username = lower(username)),
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_full_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
    CONSTRAINT ck_users_token_version CHECK (token_version >= 0)
);

CREATE TABLE courses (
    course_id bigint GENERATED BY DEFAULT AS IDENTITY,
    title varchar(255) NOT NULL,
    description text,
    teacher_id bigint NOT NULL,
    price numeric(10,2) NOT NULL DEFAULT 0,
    duration_hours integer,
    status varchar(16) NOT NULL DEFAULT 'DRAFT',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_courses PRIMARY KEY (course_id),
    CONSTRAINT fk_courses_teacher FOREIGN KEY (teacher_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_courses_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_courses_price CHECK (price >= 0),
    CONSTRAINT ck_courses_duration_hours CHECK (duration_hours IS NULL OR duration_hours > 0),
    CONSTRAINT ck_courses_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE TABLE lessons (
    lesson_id bigint GENERATED BY DEFAULT AS IDENTITY,
    course_id bigint NOT NULL,
    title varchar(255) NOT NULL,
    content_url varchar(500),
    text_content text,
    order_index integer NOT NULL,
    is_published boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_lessons PRIMARY KEY (lesson_id),
    CONSTRAINT fk_lessons_course FOREIGN KEY (course_id) REFERENCES courses(course_id) ON DELETE RESTRICT,
    CONSTRAINT ck_lessons_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_lessons_content_url CHECK (content_url IS NULL OR content_url ~* '^https?://'),
    CONSTRAINT ck_lessons_order_index CHECK (order_index >= 1)
);

CREATE TABLE enrollments (
    enrollment_id bigint GENERATED BY DEFAULT AS IDENTITY,
    student_id bigint NOT NULL,
    course_id bigint NOT NULL,
    enrollment_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status varchar(16) NOT NULL DEFAULT 'ENROLLED',
    completion_date timestamptz,
    progress_percentage numeric(5,2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_enrollments PRIMARY KEY (enrollment_id),
    CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id) REFERENCES courses(course_id) ON DELETE RESTRICT,
    CONSTRAINT uk_enrollments_student_course UNIQUE (student_id, course_id),
    CONSTRAINT ck_enrollments_status CHECK (status IN ('ENROLLED', 'COMPLETED', 'DROPPED')),
    CONSTRAINT ck_enrollments_progress CHECK (progress_percentage BETWEEN 0 AND 100),
    CONSTRAINT ck_enrollments_completion CHECK (
        (status = 'COMPLETED' AND completion_date IS NOT NULL AND progress_percentage = 100)
        OR (status <> 'COMPLETED' AND completion_date IS NULL)
    )
);

CREATE TABLE lesson_progress (
    progress_id bigint GENERATED BY DEFAULT AS IDENTITY,
    enrollment_id bigint NOT NULL,
    lesson_id bigint NOT NULL,
    is_completed boolean NOT NULL DEFAULT false,
    completed_at timestamptz,
    last_accessed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_lesson_progress PRIMARY KEY (progress_id),
    CONSTRAINT fk_lesson_progress_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollments(enrollment_id) ON DELETE RESTRICT,
    CONSTRAINT fk_lesson_progress_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(lesson_id) ON DELETE RESTRICT,
    CONSTRAINT uk_lesson_progress_enrollment_lesson UNIQUE (enrollment_id, lesson_id),
    CONSTRAINT ck_lesson_progress_completion CHECK (
        (is_completed AND completed_at IS NOT NULL)
        OR (NOT is_completed AND completed_at IS NULL)
    )
);

CREATE TABLE notifications (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    message text NOT NULL,
    type varchar(50),
    target_url varchar(500),
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_notifications PRIMARY KEY (notification_id),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_notifications_message_not_blank CHECK (btrim(message) <> ''),
    CONSTRAINT ck_notifications_target_url CHECK (
        target_url IS NULL OR (target_url LIKE '/%' AND target_url NOT LIKE '//%')
    )
);

CREATE TABLE reviews (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY,
    course_id bigint NOT NULL,
    student_id bigint NOT NULL,
    rating integer NOT NULL,
    comment text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_reviews PRIMARY KEY (review_id),
    CONSTRAINT fk_reviews_course FOREIGN KEY (course_id) REFERENCES courses(course_id) ON DELETE RESTRICT,
    CONSTRAINT fk_reviews_student FOREIGN KEY (student_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT uk_reviews_course_student UNIQUE (course_id, student_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_comment_length CHECK (comment IS NULL OR char_length(comment) <= 5000)
);

CREATE TABLE revoked_tokens (
    jti varchar(128),
    expires_at timestamptz NOT NULL,
    CONSTRAINT pk_revoked_tokens PRIMARY KEY (jti)
);

CREATE INDEX idx_courses_teacher_id ON courses (teacher_id);
CREATE INDEX idx_courses_status_created_id ON courses (status, created_at, course_id);
CREATE INDEX idx_lessons_course_order_id ON lessons (course_id, order_index, lesson_id);
CREATE INDEX idx_enrollments_course_id ON enrollments (course_id);
CREATE INDEX idx_lesson_progress_lesson_id ON lesson_progress (lesson_id);
CREATE INDEX idx_notifications_user_read_created ON notifications (user_id, is_read, created_at);
CREATE INDEX idx_reviews_student_id ON reviews (student_id);
CREATE INDEX idx_revoked_tokens_expires_at ON revoked_tokens (expires_at);
